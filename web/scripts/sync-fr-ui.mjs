#!/usr/bin/env node
/**
 * Copies the focusreactive.com UI (header, footer, buttons, forms, fonts, favicon, logos)
 * into this app, so the dispatcher looks like the main site.
 *
 * Source: the focusreactive.com-front repo (Eleventy site). Its SCSS partials are compiled
 * into app/fr-ui.css and its assets are copied to public/assets/... at the same paths the
 * site uses, so url() references in the CSS resolve unchanged.
 *
 *   node scripts/sync-fr-ui.mjs [--repo=../../focusreactive.com-front] [--ref=origin/main]
 *
 * Reads files with `git archive <ref>`, so the other repo's working tree is never touched.
 * Run `git -C <repo> fetch` first to pick up the latest site design.
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as sass from 'sass';

const webDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, ...v] = a.replace(/^--/, '').split('=');
    return [k, v.join('=')];
  }),
);
const repo = resolve(args.repo || join(webDir, '../../focusreactive.com-front'));
const ref = args.ref || 'origin/main';

// Partials the dispatcher uses. Order follows the site's style.scss.
const SCSS_MODULES = [
  'normalize',
  'fonts',
  'layout',
  'ui/buttons',
  'ui/forms',
  'ui/links',
  'ui/socials',
  'common',
  'partials/header',
  'partials/footer',
  'partials/contacts',
];

const FONT_FACES = ['Regular', 'Medium', 'SemiBold', 'Bold'];
const ASSETS = [
  'src/assets/img/favicon.ico',
  'src/assets/img/fr-logo.svg',
  'src/assets/img/fr-logo-footer.svg',
  'src/assets/img/clutch.svg',
  'src/assets/img/footer-bg.webp',
  ...FONT_FACES.flatMap((f) => [
    `src/assets/fonts/InterDisplay-${f}.subset.woff2`,
    `src/assets/fonts/InterDisplay-${f}.woff2`,
  ]),
];

// Social icons live in the CMS, not the repo; the site serves them from /media/posts/.
const SOCIAL_ICONS = [
  'b2c5913902aa-x-logo.svg',
  '6571067e5f1b-linkedin1.svg',
  '5cb8f4534057-youtube1.svg',
  '9201be7f0f20-github1.svg',
];

const tmp = mkdtempSync(join(tmpdir(), 'fr-ui-'));
try {
  const rev = execFileSync('git', ['-C', repo, 'rev-parse', '--short', ref], { encoding: 'utf8' }).trim();
  const archive = execFileSync('git', ['-C', repo, 'archive', ref, 'src/sassNew', ...ASSETS], {
    maxBuffer: 256 * 1024 * 1024,
  });
  execFileSync('tar', ['-x', '-C', tmp], { input: archive });

  const entry = SCSS_MODULES.map((m) => `@use '${m}';`).join('\n');
  const { css } = sass.compileString(entry, {
    loadPaths: [join(tmp, 'src/sassNew')],
    style: 'expanded',
    silenceDeprecations: ['import', 'global-builtin', 'color-functions'],
  });
  const header =
    `/* Generated by scripts/sync-fr-ui.mjs from focusreactive.com-front@${rev} (src/sassNew). */\n` +
    `/* Do not edit by hand: change the site's SCSS, then re-run the script. */\n`;
  writeFileSync(join(webDir, 'app/fr-ui.css'), header + css + '\n');

  for (const asset of ASSETS) {
    if (asset.endsWith('favicon.ico')) continue; // served by Next from app/favicon.ico
    const out = join(webDir, 'public', asset.replace(/^src\//, ''));
    mkdirSync(dirname(out), { recursive: true });
    copyFileSync(join(tmp, asset), out);
  }
  copyFileSync(join(tmp, 'src/assets/img/favicon.ico'), join(webDir, 'app/favicon.ico'));

  mkdirSync(join(webDir, 'public/media/posts'), { recursive: true });
  for (const icon of SOCIAL_ICONS) {
    const res = await fetch(`https://focusreactive.com/media/posts/${icon}`);
    if (!res.ok) throw new Error(`social icon ${icon}: HTTP ${res.status}`);
    writeFileSync(join(webDir, 'public/media/posts', icon), Buffer.from(await res.arrayBuffer()));
  }

  console.log(
    `Synced focusreactive.com UI from ${ref} (${rev}): app/fr-ui.css, ${ASSETS.length} assets, ${SOCIAL_ICONS.length} icons`,
  );
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
